import { test, expect } from '@playwright/test';
import { workspace } from './helpers/marketing-workspace.js';

for (const width of [1440, 390]) for (const automatic of [false, true]) test(`owner prepares source-bound charts ${automatic ? 'by editorial rule' : 'with the team'} at ${width}px`, async ({ page }, info) => {
  test.setTimeout(90000);
  await page.setViewportSize({ width, height: 950 });
  await page.addInitScript(theme => localStorage.setItem('uz_stock_analyzer_theme', theme), width === 390 ? 'light' : 'dark');
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const callApi = await workspace(page, info), base = '/api/admin/ai-marketing';
  const fixture = callApi({ method: 'CHART_SOURCE_FIXTURE' });
  expect(fixture.status).toBe(200);
  const original = fixture.body.evidence;
  await page.reload();
  await page.getByRole('button', { name: 'Рабочий цикл', exact: true }).click();
  if (automatic) {
    await page.getByRole('button', { name: 'Добавить редакционное правило', exact: true }).click();
    const dialog = page.getByRole('dialog');
    await dialog.getByLabel('Название правила', { exact: true }).fill('Проверенные цены HMKB');
    await dialog.getByLabel('Рубрика', { exact: true }).selectOption('chart');
    const field = dialog.getByLabel('Поле ряда в оригинале', { exact: true });
    await expect(field).toHaveAccessibleDescription(/единиц/);
    await field.fill('close');
    await expect(dialog.getByLabel('Формат', { exact: true }).locator('option[value="post"]')).toHaveCount(0);
    await dialog.getByRole('checkbox', { name: 'O‘zbekcha', exact: true }).check();
    await dialog.getByRole('group', { name: 'Разрешённые источники', exact: true }).getByRole('checkbox').check();
    await dialog.getByLabel('Включить автоматический выбор', { exact: true }).check();
    await field.focus();
    await expect(field).toBeFocused();
    await field.evaluate(el => el.scrollIntoView({ block: 'center', behavior: 'instant' }));
    await page.screenshot({ path: info.outputPath(`chart-rule-${width}.png`) });
    await dialog.getByRole('button', { name: 'Сохранить правило', exact: true }).click();
    await expect(dialog).toHaveCount(0);
    const rule = page.getByRole('article', { name: 'Проверенные цены HMKB', exact: true });
    await expect(rule).toContainText('close');
    expect(callApi({ method: 'WORKER_STEP' }).body.editorial_work).toBe(true);
  } else {
    const form = page.locator('form').filter({ has: page.getByLabel('Задание команде', { exact: true }) });
    await form.getByLabel('Задание команде', { exact: true }).fill('Объяснить изменение цены за указанные даты без прогноза.');
    await form.getByLabel('Ключ события', { exact: true }).fill('owner-chart-hmkb');
    await form.getByLabel('Рубрика задания', { exact: true }).selectOption('chart');
    await form.getByLabel('Эмитент или тикер', { exact: true }).fill('HMKB');
    await form.getByLabel('Период задания', { exact: true }).fill(original.period);
    await form.getByLabel('Точная ссылка для читателя', { exact: true }).fill(original.destination_url);
    await form.getByLabel('Подготовить для UZStock test', { exact: true }).check();
    await expect(form.getByLabel('Формат · UZStock test', { exact: true }).locator('option[value="post"]')).toHaveCount(0);
    const series = form.getByLabel('Ряд графика', { exact: true });
    await expect(series).toBeVisible();
    await expect(form.getByRole('button', { name: 'Передать команде', exact: true })).toBeDisabled();
    const proof = form.getByRole('group', { name: 'Исходные оригиналы', exact: true });
    await proof.getByLabel(original.title, { exact: true }).check();
    await series.selectOption({ label: `${original.title} · close · UZS/share` });
    await proof.getByLabel(original.title, { exact: true }).uncheck();
    await expect(series).toHaveValue('');
    await expect(form.getByRole('button', { name: 'Передать команде', exact: true })).toBeDisabled();
    await proof.getByLabel(original.title, { exact: true }).check();
    await series.selectOption({ label: `${original.title} · close · UZS/share` });
    await series.focus();
    await expect(series).toBeFocused();
    await series.evaluate(el => el.scrollIntoView({ block: 'center', behavior: 'instant' }));
    await page.screenshot({ path: info.outputPath(`chart-team-${width}.png`) });
    await form.getByRole('button', { name: 'Передать команде', exact: true }).click();
    await expect(form.getByLabel('Задание команде', { exact: true })).toHaveValue('');
  }
  expect(callApi({ method: 'MODEL_PRODUCTION', chart: true }).status).toBe(200);
  await page.reload();
  await page.getByRole('button', { name: 'Контент и очередь', exact: true }).click();
  const card = page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Как менялась цена?', exact: true }) });
  await expect(card).toContainText('Черновик');
  await card.getByRole('button', { name: 'Открыть медиа', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog.getByRole('img')).toBeVisible();
  await dialog.getByText('Данные и шкала графика', { exact: true }).click();
  await expect(dialog.getByRole('table')).toContainText('2026-11-20');
  await expect(dialog.getByRole('table')).toContainText('100');
  await dialog.getByRole('img').evaluate(el => el.scrollIntoView({ block: 'center', behavior: 'instant' }));
  await page.screenshot({ path: info.outputPath(`chart-result-${automatic}-${width}.png`) });
  await dialog.getByRole('button', { name: 'Закрыть', exact: true }).click();
  await page.getByRole('button', { name: 'Рабочий цикл', exact: true }).click();
  if (automatic) {
    const rule = page.getByRole('article', { name: 'Проверенные цены HMKB', exact: true });
    await rule.getByRole('button', { name: 'Изменить правило', exact: true }).click();
    await expect(dialog.getByLabel('Поле ряда в оригинале', { exact: true })).toHaveValue('close');
    await dialog.getByRole('button', { name: 'Закрыть', exact: true }).click();
    await rule.getByRole('button', { name: 'Отключить правило', exact: true }).click();
    await expect(rule).toContainText('Отключён');
  }
  const state = callApi({ method: 'GET', path: `${base}/workspace` }).body;
  expect(state.tasks).toHaveLength(1);
  expect(state.tasks[0].production.chart).toEqual({ evidence_id: original.id, field: 'close' });
  expect(state.tasks[0].status).toBe('complete');
  expect(state.variants).toHaveLength(2);
  expect(state.candidates).toHaveLength(1);
  expect(state.candidates[0].check.passed).toBe(true);
  expect(state.assets).toHaveLength(2);
  expect(state.assets.every(asset => asset.chart.field === 'close')).toBe(true);
  expect(state.deliveries).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
