import { test, expect } from '@playwright/test';
import { workspace } from './helpers/marketing-workspace.js';

for (const width of [1440, 390]) test(`owner registers, measures and decides an organic format comparison at ${width}px`, async ({ page }, info) => {
  test.setTimeout(90000);
  await page.setViewportSize({ width, height: 950 });
  await page.addInitScript(theme => localStorage.setItem('uz_stock_analyzer_theme', theme), width === 390 ? 'light' : 'dark');
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const callApi = await workspace(page, info);
  const fixture = callApi({ method: 'EDITORIAL_EXPERIMENT_FIXTURE' });
  expect(fixture.status).toBe(200);
  const design = fixture.body.design;
  await page.reload();
  await page.getByRole('button', { name: 'Эксперименты', exact: true }).click();
  await page.getByRole('button', { name: 'Новый тест рубрики', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Дизайн теста рубрики', exact: true });
  for (const [label, key] of Object.entries({ 'Название теста': 'title', 'Гипотеза': 'hypothesis', 'Сегмент читателей': 'segment', 'Вопрос читателя': 'reader_question', 'Единственная переменная': 'tested_variable', 'Условия сравнения': 'comparison', 'Условие прекращения': 'stop_condition', 'Начало набора': 'starts_on', 'Конец набора, не включая': 'ends_on', 'Объект целевого действия': 'outcome_object_id' })) {
    await dialog.getByLabel(label, { exact: true }).fill(design[key]);
  }
  await dialog.getByLabel('Целевое действие', { exact: true }).selectOption('news_open');
  await dialog.getByLabel('Дней наблюдения после перехода', { exact: true }).fill('1');
  await dialog.getByLabel('Минимум читателей в каждом варианте', { exact: true }).fill('4');
  await dialog.getByLabel('Контроль · публикации', { exact: true }).selectOption(design.control_ids);
  await dialog.getByLabel('Новый вариант · публикации', { exact: true }).selectOption(design.control_ids);
  await dialog.getByRole('button', { name: 'Зафиксировать дизайн', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('Проверьте поля формы');
  await dialog.getByLabel('Новый вариант · публикации', { exact: true }).selectOption(design.variant_ids);
  await dialog.getByLabel('Контроль · публикации', { exact: true }).evaluate(el => el.scrollIntoView({ block: 'center', behavior: 'instant' }));
  await page.screenshot({ path: info.outputPath(`editorial-experiment-design-${width}.png`) });
  await dialog.getByRole('button', { name: 'Зафиксировать дизайн', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  const card = page.getByRole('article', { name: design.title, exact: true });
  await expect(card).toContainText('Ретроспективное сравнение');
  await card.getByRole('button', { name: 'Рассчитать и сохранить оценку', exact: true }).click();
  await expect(card).toContainText('Предварительный результат');
  const table = card.getByRole('table', { name: 'Измеренные результаты', exact: true });
  await expect(table.getByRole('row', { name: /Контроль/ }).getByRole('cell').last()).toHaveText('33,333');
  await expect(table.getByRole('row', { name: /Новый вариант/ }).getByRole('cell').last()).toHaveText('66,667');
  await expect(card).toContainText('Недостаточно читателей');
  await table.evaluate(el => el.scrollIntoView({ block: 'center', behavior: 'instant' }));
  await page.screenshot({ path: info.outputPath(`editorial-experiment-${width}.png`) });
  if (width === 390) {
    const scroller = card.getByRole('region', { name: 'Результаты: прокрутка по горизонтали', exact: true });
    await scroller.focus();
    await page.keyboard.press('ArrowRight');
    await expect.poll(() => scroller.evaluate(el => el.scrollLeft)).toBeGreaterThan(0);
    await scroller.evaluate(el => { el.scrollLeft = el.scrollWidth; });
    expect(await table.evaluate(el => {
      const value = el.querySelector('tbody tr td:last-child').getBoundingClientRect();
      const container = el.parentElement.getBoundingClientRect();
      return value.left >= container.left && value.right <= container.right+1;
    })).toBe(true);
    await page.screenshot({ path: info.outputPath('editorial-experiment-rates-390.png') });
  }
  await card.getByLabel('Решение по формату', { exact: true }).selectOption('change');
  await card.getByLabel('Обоснование решения', { exact: true }).fill('Увеличить выборку в следующем тесте; вывод пока предварительный.');
  await card.getByRole('button', { name: 'Сохранить решение по оценке', exact: true }).click();
  await expect(card).toContainText('Сохранённое решение: Изменить');
  await page.reload();
  await expect(card).toContainText('Увеличить выборку в следующем тесте');
  await expect(card).toContainText('Предварительный результат');
  const state = callApi({ method: 'GET', path: '/api/admin/ai-marketing/workspace' }).body;
  expect(state.active_goal.target).toBe(100);
  expect(state.active_goal.budget).toBe(0);
  expect(state.deliveries).toEqual([]);
  expect(state.editorial_experiments[0].decision.evaluation_id).toBe(state.experiment_evaluations[0].id);
  const original = state.experiment_evaluations[0];
  const corrected = callApi({ method: 'POST', path: '/api/admin/ai-marketing/reports/import', body: { corrections: [{ event_id: 'variant-open-1', dataset: 'test', replacement: null, reason: 'Отозван ошибочный receipt', expected_version: 0 }] } });
  expect(corrected.status).toBe(200);
  await card.getByRole('button', { name: 'Рассчитать и сохранить оценку', exact: true }).click();
  await expect(card).toContainText('Решение относится к другому сохранённому срезу');
  await expect(table.getByRole('row', { name: /Новый вариант/ }).getByRole('cell').last()).toHaveText('33,333');
  await card.getByLabel('Сохранённая оценка', { exact: true }).selectOption(original.id);
  await expect(table.getByRole('row', { name: /Новый вариант/ }).getByRole('cell').last()).toHaveText('66,667');
  await expect(card).not.toContainText('Решение относится к другому сохранённому срезу');
  await card.getByRole('button', { name: 'История решений', exact: true }).click();
  const history = page.getByRole('dialog', { name: 'История решений по тесту', exact: true });
  await expect(history).toContainText('Увеличить выборку в следующем тесте');
  await expect(history).toContainText('Дизайн зарегистрирован');
  const reference = await history.getByText(`Сохранённая оценка: ${original.id}`, { exact: true }).boundingBox();
  const actor = await history.locator('li').last().getByText('Роль: administrator', { exact: true }).boundingBox();
  expect(actor.y).toBeGreaterThanOrEqual(reference.y+reference.height);
  expect(await history.evaluate(el => el.scrollWidth <= el.clientWidth+1)).toBe(true);
  await page.screenshot({ path: info.outputPath(`editorial-experiment-history-${width}.png`) });
  await history.getByRole('button', { name: 'Закрыть', exact: true }).click();
  await page.getByRole('button', { name: 'Отчёты', exact: true }).click();
  await page.getByLabel('Начало отчёта', { exact: true }).fill(design.starts_on);
  await page.getByLabel('Конец отчёта, не включая', { exact: true }).fill(design.ends_on);
  await page.getByRole('button', { name: 'Рассчитать период', exact: true }).click();
  const report = page.getByRole('region', { name: 'Оценки тестов рубрик', exact: true });
  await expect(report).toContainText(design.title);
  await expect(report).toContainText('Предварительный');
  await expect(report).toContainText('Увеличить выборку в следующем тесте');
  await report.evaluate(el => el.scrollIntoView({ block: 'center', behavior: 'instant' }));
  await page.screenshot({ path: info.outputPath(`editorial-experiment-report-${width}.png`) });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
