import { test, expect } from '@playwright/test';
import { workspace } from './helpers/marketing-workspace.js';

for (const width of [1440, 390]) test(`weekly calendar binds announcements and preserves owner edits at ${width}px`, async ({ page }, info) => {
  test.setTimeout(90000);
  await page.setViewportSize({ width, height: 950 });
  await page.addInitScript(theme => localStorage.setItem('uz_stock_analyzer_theme', theme), width === 390 ? 'light' : 'dark');
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const callApi = await workspace(page, info), base = '/api/admin/ai-marketing';
  const fixture = callApi({ method: 'CALENDAR_SOURCE_FIXTURE' }).body;
  const cutoff = new Date().toLocaleTimeString('en-GB', { timeZone: 'Asia/Tashkent', hour: '2-digit', minute: '2-digit' });
  await page.reload();
  await page.getByRole('button', { name: 'Рабочий цикл', exact: true }).click();
  await page.getByRole('button', { name: 'Добавить редакционное правило', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Название правила', { exact: true }).fill('Календарь этой недели');
  await dialog.getByLabel('Рубрика', { exact: true }).selectOption('calendar');
  await expect(dialog.getByLabel('День подбора календаря', { exact: true })).toBeVisible();
  await dialog.getByLabel('День подбора календаря', { exact: true }).selectOption(String(fixture.weekday));
  await dialog.getByLabel('Время подбора календаря · Ташкент', { exact: true }).fill(cutoff);
  await expect(dialog.getByLabel('Возраст события, часов', { exact: true })).toHaveCount(0);
  await expect(dialog.getByLabel('Формат', { exact: true })).toHaveValue('post');
  await dialog.getByRole('group', { name: 'Разрешённые источники', exact: true }).getByRole('checkbox').check();
  await dialog.getByLabel('Включить автоматический выбор', { exact: true }).check();
  await dialog.getByLabel('День подбора календаря', { exact: true }).evaluate(el => el.scrollIntoView({ block: 'center', behavior: 'instant' }));
  await page.screenshot({ path: info.outputPath(`marketing-calendar-rule-${width}.png`) });
  await dialog.getByRole('button', { name: 'Сохранить правило', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  const rule = page.getByRole('article', { name: 'Календарь этой недели', exact: true });
  await expect(rule).toContainText('Еженедельный календарь');
  expect(callApi({ method: 'WORKER_STEP' }).body.editorial_work).toBe(true);
  expect(callApi({ method: 'MODEL_PRODUCTION', calendar: true }).status).toBe(200);
  await page.reload();
  await page.getByRole('button', { name: 'Контент и очередь', exact: true }).click();
  const card = page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Календарь объявленных событий', exact: true }) });
  await expect(card).toContainText('Черновик');
  await expect(card).toContainText('Собрание');
  await expect(card).toContainText('Отчёт');
  await card.getByRole('button', { name: 'Изменить материал', exact: true }).click();
  await expect(dialog.getByRole('button', { name: 'Добавить пункт календаря', exact: true })).toBeVisible();
  await expect(dialog.getByLabel('Текст пункта 1', { exact: true })).toHaveValue(fixture.evidence[0].excerpt);
  const edit = 'Проверьте опубликованную повестку собрания и условия участия в первоисточнике.';
  await dialog.getByLabel('Текст пункта 1', { exact: true }).fill(edit);
  await dialog.getByLabel('Текст пункта 1', { exact: true }).evaluate(el => el.scrollIntoView({ block: 'center', behavior: 'instant' }));
  await page.screenshot({ path: info.outputPath(`marketing-calendar-editor-${width}.png`) });
  await dialog.getByRole('button', { name: 'Сохранить материал', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(card).toContainText(edit);
  await card.getByRole('button', { name: 'Проверить факты', exact: true }).click();
  await card.locator('h4').evaluate(el => el.scrollIntoView({ block: 'start', behavior: 'instant' }));
  await page.screenshot({ path: info.outputPath(`marketing-calendar-material-${width}.png`) });
  await page.reload();
  await page.getByRole('button', { name: 'Рабочий цикл', exact: true }).click();
  await rule.getByRole('button', { name: 'Изменить правило', exact: true }).click();
  await expect(dialog.getByLabel('День подбора календаря', { exact: true })).toHaveValue(String(fixture.weekday));
  await expect(dialog.getByLabel('Время подбора календаря · Ташкент', { exact: true })).toHaveValue(cutoff);
  await dialog.getByRole('button', { name: 'Закрыть', exact: true }).click();
  expect(callApi({ method: 'WORKER_STEP' }).body.editorial_work).toBe(false);
  await rule.getByRole('button', { name: 'Отключить правило', exact: true }).click();
  await expect(rule).toContainText('Отключён');
  const final = callApi({ method: 'GET', path: `${base}/workspace` }).body;
  expect(final.candidates).toHaveLength(1);
  expect(final.candidates[0].check.passed).toBe(true);
  expect(final.candidates[0].digest_items).toHaveLength(2);
  expect(final.candidates[0].period).toBe(fixture.week);
  for (const original of fixture.evidence) {
    expect(final.candidates[0].body).toContain(original.url);
    expect(final.candidates[0].body).toContain(new Date(original.event_at).toLocaleDateString('ru-RU', { timeZone: 'Asia/Tashkent' }));
  }
  expect(final.deliveries).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
