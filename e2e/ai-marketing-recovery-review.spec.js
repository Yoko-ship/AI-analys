import { test, expect } from '@playwright/test';
import { workspace } from './helpers/marketing-workspace.js';

for (const width of [1440, 390]) test(`owner reviews the backup gap and quarantines old work at ${width}px`, async ({ page }, info) => {
  test.setTimeout(90000);
  await page.setViewportSize({ width, height: 950 });
  await page.addInitScript(theme => localStorage.setItem('uz_stock_analyzer_theme', theme), width === 390 ? 'light' : 'dark');
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const callApi = await workspace(page, info), base = '/api/admin/ai-marketing';
  expect(callApi({ method: 'RESTORE_REHEARSAL', prepared: true }).status).toBe(200);
  await page.reload();
  const region = page.getByRole('region', { name: 'Восстановление очереди', exact: true });
  await expect(region).toContainText('Сверка после восстановления');
  await region.getByRole('button', { name: 'Проверить промежуток после копии', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog).toContainText('Старый внутренний черновик');
  await expect(dialog).toContainText('-100123');
  await expect(dialog.getByRole('button', { name: 'Завершить сверку и закрыть прежние выпуски', exact: true })).toBeDisabled();
  await dialog.getByLabel('Старый обработчик остановлен и больше не отправляет публикации', { exact: true }).check();
  await dialog.getByLabel('Основание сверки аккаунта 1', { exact: true }).fill('Проверена история Telegram за весь промежуток. Найден один выпуск, отсутствующий в копии.');
  await dialog.getByLabel('Итог сверки', { exact: true }).fill('Неподтверждённые прежние версии остаются закрытыми. Новый выпуск из промежутка зарезервирован.');
  await dialog.getByRole('button', { name: 'Добавить найденную публикацию', exact: true }).click();
  const publication = dialog.getByRole('group', { name: 'Найденная публикация 1', exact: true });
  await publication.getByLabel('Ключ события', { exact: true }).fill('event-created-after-backup');
  await publication.getByLabel('Ссылка на публикацию', { exact: true }).fill('https://t.me/example/124');
  const state = callApi({ method: 'GET', path: `${base}/workspace` }).body;
  const at = new Date(new Date(state.recovery.backup_created_at).getTime() + 5 * 3600000 + 60000).toISOString().slice(0, 16);
  await publication.getByLabel('Опубликовано · Ташкент', { exact: true }).fill(at);
  await publication.evaluate(el => el.scrollIntoView({ block: 'center', behavior: 'instant' }));
  await page.screenshot({ path: info.outputPath(`marketing-recovery-review-${width}.png`) });
  await dialog.getByRole('button', { name: 'Завершить сверку и закрыть прежние выпуски', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(region).toContainText('Сверка восстановления завершена');
  const final = callApi({ method: 'GET', path: `${base}/workspace` }).body;
  expect(final.recovery.status).toBe('reconciled');
  expect(final.pause.publications && final.pause.processing).toBe(true);
  expect(final.candidates.every(item => item.status === 'unknown')).toBe(true);
  expect(final.deliveries.every(item => item.status === 'unknown')).toBe(true);
  expect(final.accounts[0].connection_status).toBe('not_connected');
  await page.getByRole('button', { name: 'Контент и очередь', exact: true }).click();
  const old = page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Старый внутренний черновик', exact: true }) });
  await expect(old).toContainText('Исход неясен');
  await expect(old).toContainText('повторной отправки');
  await expect(old.getByRole('button', { name: 'Поставить в очередь', exact: true })).toHaveCount(0);
  await old.evaluate(el => el.scrollIntoView({ block: 'center', behavior: 'instant' }));
  await page.screenshot({ path: info.outputPath(`marketing-recovery-quarantine-${width}.png`) });
  await page.reload();
  await region.getByText('Сверка восстановления завершена', { exact: true }).click();
  await region.getByRole('button', { name: 'История восстановления', exact: true }).click();
  await expect(dialog).toContainText('Новый выпуск из промежутка зарезервирован');
  expect(callApi({ method: 'DISPATCH_STEP', at: new Date().toISOString() }).body.dispatched).toBe(false);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
