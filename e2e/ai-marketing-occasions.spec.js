import { test, expect } from '@playwright/test';
import { workspace } from './helpers/marketing-workspace.js';

for (const [width, kind] of [[390, 'holiday'], [1440, 'gaming']]) test(`confirmed ${kind} brief preserves its source through editing at ${width}px`, async ({ page }, info) => {
  test.setTimeout(90000);
  await page.setViewportSize({ width, height: 950 });
  await page.addInitScript(theme => localStorage.setItem('uz_stock_analyzer_theme', theme), width === 390 ? 'light' : 'dark');
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const callApi = await workspace(page, info), base = '/api/admin/ai-marketing';
  const fixture = callApi({ method: 'OCCASION_SOURCE_FIXTURE', kind }).body;
  await page.reload();
  await page.getByRole('button', { name: 'Рабочий цикл', exact: true }).click();
  await page.getByLabel('Задание команде', { exact: true }).fill('Подготовьте полезное объяснение по подтверждённому поводу без выдуманных рыночных фактов.');
  await page.getByLabel('Ключ события', { exact: true }).fill(`occasion-${kind}`);
  await page.getByLabel('Точная ссылка для читателя', { exact: true }).fill('https://uzstock.uz/news/occasion');
  await page.getByLabel('Подготовить для UZStock test', { exact: true }).check();
  await page.getByLabel('Формат · UZStock test', { exact: true }).selectOption('image');
  await page.getByLabel('Повод и подача', { exact: true }).selectOption(kind);
  await expect(page.getByRole('button', { name: 'Передать команде', exact: true })).toBeDisabled();
  await page.getByRole('group', { name: 'Исходные оригиналы', exact: true }).getByRole('checkbox').check();
  await page.getByLabel('Оригинал повода', { exact: true }).selectOption('occasion');
  await expect(page.getByLabel('Оригинал повода', { exact: true })).toHaveAccessibleDescription(/верси/);
  await page.getByLabel('Повод и подача', { exact: true }).evaluate(el => el.scrollIntoView({ block: 'center', behavior: 'instant' }));
  await page.screenshot({ path: info.outputPath(`marketing-occasion-brief-${width}.png`) });
  await page.getByRole('button', { name: 'Передать команде', exact: true }).click();
  await expect(page.getByText('Команда получила задание. Каждый шаг и вариант сохраняется на сервере.', { exact: true })).toBeVisible();
  expect(callApi({ method: 'MODEL_PRODUCTION', occasion: true }).status).toBe(200);
  await page.reload();
  await page.getByRole('button', { name: 'Контент и очередь', exact: true }).click();
  const title = kind === 'holiday' ? 'К празднику — спокойная проверка' : 'Одна свеча — не весь сюжет';
  const card = page.getByRole('article').filter({ has: page.getByRole('heading', { name: title, exact: true }) });
  await expect(card).toContainText(kind === 'holiday' ? 'Праздничная подача' : 'Игровой инфоповод');
  await expect(card).toContainText('Автоматические проверки пройдены');
  await card.getByRole('button', { name: 'Открыть медиа', exact: true }).click();
  const dialog = page.getByRole('dialog');
  const picture = dialog.locator('img');
  await expect(picture).toHaveCount(1);
  await expect(picture).toBeVisible();
  await expect.poll(() => picture.evaluate(img => img.complete && img.naturalWidth > 0)).toBe(true);
  await page.screenshot({ path: info.outputPath(`marketing-occasion-media-${width}.png`) });
  await dialog.getByRole('button', { name: 'Закрыть', exact: true }).click();
  await card.getByRole('button', { name: 'Изменить материал', exact: true }).click();
  await expect(dialog.getByLabel('Повод и подача', { exact: true })).toHaveValue(kind);
  await expect(dialog.getByLabel('Оригинал повода', { exact: true })).toHaveValue('occasion');
  await dialog.getByLabel('Текст публикации', { exact: true }).fill(kind === 'holiday' ? 'В праздник биржа закрыта.' : 'Релиз игры вызвал рост акций.');
  await dialog.getByRole('button', { name: 'Сохранить материал', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await card.getByRole('button', { name: 'Проверить факты', exact: true }).click();
  await expect(card).toContainText('Нужна доработка');
  await expect(card).toContainText(kind === 'holiday' ? 'расписание биржи' : 'влияние на рынок');
  await card.locator('.mkt-error').evaluate(el => el.scrollIntoView({ block: 'center', behavior: 'instant' }));
  await page.screenshot({ path: info.outputPath(`marketing-occasion-rejected-${width}.png`) });
  await page.reload();
  const state = callApi({ method: 'GET', path: `${base}/workspace` }).body;
  expect(state.candidates[0].occasion).toEqual(fixture.occasion);
  expect(state.tasks[0].production.occasion).toEqual(fixture.occasion);
  expect(state.deliveries).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
