import { test, expect } from '@playwright/test';
import { workspace } from './helpers/marketing-workspace.js';

for (const width of [1440, 390]) test(`an open reporting period preserves observations without claiming a full goal result at ${width}px`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 950 });
  await page.addInitScript(theme => localStorage.setItem('uz_stock_analyzer_theme', theme), width === 390 ? 'light' : 'dark');
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const callApi = await workspace(page, info);
  const fixture = callApi({ method: 'REPORT_GOAL_FIXTURE' });
  expect(fixture.status).toBe(200);
  await page.reload();
  await page.getByRole('button', { name: 'Отчёты', exact: true }).click();
  await page.getByLabel('Показать снимок', { exact: true }).selectOption(fixture.body.snapshot_id);
  const panel = page.locator('.mkt-panel').filter({ has: page.getByRole('heading', { name: 'Цель и план-факт', exact: true }) });
  await expect(panel).toContainText('Период ещё не завершён');
  await expect(panel).toContainText('Наблюдаемое значение на дату среза: 30');
  await expect(panel).toContainText('Не сопоставляем');
  await expect(panel).not.toContainText('-70');
  await panel.evaluate(el => el.scrollIntoView({ block: 'center', behavior: 'instant' }));
  await page.screenshot({ path: info.outputPath(`marketing-open-week-${width}.png`) });
  await page.reload();
  await page.getByLabel('Показать снимок', { exact: true }).selectOption(fixture.body.snapshot_id);
  await expect(panel).toContainText('Наблюдаемое значение на дату среза: 30');
  const state = callApi({ method: 'GET', path: '/api/admin/ai-marketing/workspace' }).body;
  expect(state.active_goal.target).toBe(100);
  expect(state.snapshots[0].report.plan_fact.actual).toBeNull();
  expect(state.snapshots[0].report.metrics.registrations.value).toBe(30);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});

for (const width of [1440, 390]) test(`CMO decisions show their measured basis and hypothesis tree without changing the goal at ${width}px`, async ({ page }, info) => {
  test.setTimeout(90000);
  await page.setViewportSize({ width, height: 950 });
  await page.addInitScript(theme => localStorage.setItem('uz_stock_analyzer_theme', theme), width === 390 ? 'light' : 'dark');
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const callApi = await workspace(page, info);
  const fixture = callApi({ method: 'REPORT_GOAL_FIXTURE', closed: true });
  expect(fixture.status).toBe(200);
  await page.reload();
  await page.getByRole('button', { name: 'Отчёты', exact: true }).click();
  await page.getByLabel('Начало отчёта', { exact: true }).fill(fixture.body.period.starts_on);
  await page.getByLabel('Конец отчёта, не включая', { exact: true }).fill(fixture.body.period.ends_on);
  await page.getByRole('button', { name: 'Рассчитать период', exact: true }).click();
  await page.getByRole('button', { name: 'Запросить анализ CMO', exact: true }).click();
  callApi({ method: 'MODEL_STEP' });
  callApi({ method: 'MODEL_STEP' });
  await page.getByRole('button', { name: 'Обновить отчёт', exact: true }).click();
  const review = page.getByRole('region', { name: 'Решения CMO', exact: true });
  await expect(review).toBeVisible();
  await expect(page.getByRole('region', { name: 'Выводы команды', exact: true })).not.toContainText('Новый анализ: В очереди');
  await expect(review).toContainText('Предложения не меняют цель');
  await expect(review).toContainText('Тестовые данные');
  await expect(review.getByRole('table', { name: 'Основания решений', exact: true }).getByRole('row', { name: /Регистрации/ })).toContainText('30');
  const decision = review.getByRole('article', { name: 'Подготовка следующего контент-теста', exact: true });
  await expect(decision).toContainText('Изменить');
  await expect(decision).toContainText('Сравнить два варианта обложки');
  await expect(decision).toContainText('Data / Web-аналитик');
  await decision.evaluate(el => el.scrollIntoView({ block: 'center', behavior: 'instant' }));
  await page.screenshot({ path: info.outputPath(`marketing-cmo-decision-${width}.png`) });
  const hypotheses = review.getByRole('group', { name: 'Дерево гипотез', exact: true });
  await expect(hypotheses).toContainText('Конкретный вопрос на обложке');
  await expect(hypotheses).toContainText('Развивает гипотезу');
  await hypotheses.evaluate(el => el.scrollIntoView({ block: 'center', behavior: 'instant' }));
  await page.screenshot({ path: info.outputPath(`marketing-cmo-hypotheses-${width}.png`) });
  await page.getByLabel('Название снимка', { exact: true }).fill('Решения CMO за неделю');
  await page.getByRole('button', { name: 'Зафиксировать неделю', exact: true }).click();
  const state = callApi({ method: 'GET', path: '/api/admin/ai-marketing/workspace' }).body;
  const frozen = state.snapshots.find(row => row.name === 'Решения CMO за неделю');
  expect(frozen.report.analysis.cmo.cmo_review.basis.metrics.registrations.value).toBe(30);
  expect(frozen.report.analysis.cmo.cmo_review.basis.plan_fact.difference).toBe(-70);
  expect(state.active_goal.target).toBe(100);
  expect(state.active_goal.budget).toBe(0);
  expect(state.deliveries).toEqual([]);
  await page.reload();
  await page.getByLabel('Показать снимок', { exact: true }).selectOption(frozen.id);
  await expect(review).toContainText('Сравнить два варианта обложки');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
